#!/usr/bin/env python3
"""Every game's launcher picture: games/<game>/art/launcher.png -> games/<game>/launcher_icon.h.

The launcher (shell/launcher.h) shows six games a page as picture tiles, ICON_W x ICON_H inside a 1 px border, in the
shell's indexed 32-color palette (os/palette.h). Each PNG came from Codex's built-in image generator, with that game's
own screen attached so the picture keeps the game's look (prompts: docs/launcher/README.md). The picture is center
cropped to the tile's shape, every source pixel is mapped to its nearest palette color by a weighted distance, and
each cell takes the color most of its pixels voted for: integer math only, so --check is byte-identical on every machine. Needs Pillow.
  python3 tools/launcher_icons.py           regenerate every header
  python3 tools/launcher_icons.py --check   fail if any header is stale

TODO: Kingdom (kingdom_art.py), Toy Town (toytown_art.py) and Pets Club (art.py) still generate their old 24-32 px
icons, now unused; drop them from those generators (and their pinned manifests) the next time each is touched.
"""

import re
import sys
from collections import Counter
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ICON_W, ICON_H = 38, 28  # launcher::TILE_W - 2 by launcher::TILE_H - 2
GAMES = ("pets-club", "biscuit", "marble-kick", "tilt-fc", "pumpkin-hide-seek", "plane-radar", "starfighter", "living-kingdom", "toy-town-life", "racing")


def palette():
    block = (ROOT / "os/palette.h").read_text().split("PALETTE_RGB[C_COUNT] = {")[1].split("};")[0]
    return [tuple(bytes.fromhex(v)) for v in re.findall(r"0x([0-9A-Fa-f]{6})", block)]


def nearest(p, pal):  # green weighs most, blue least: closest to how the eye ranks the 32 colors
    return min(range(len(pal)), key=lambda i: 3 * (p[0] - pal[i][0]) ** 2 + 4 * (p[1] - pal[i][1]) ** 2 + 2 * (p[2] - pal[i][2]) ** 2)


def pixels(path, pal):
    img = Image.open(path).convert("RGB")
    w, h = img.size
    cw = min(w, h * ICON_W // ICON_H)
    ch = cw * ICON_H // ICON_W
    x0, y0 = (w - cw) // 2, (h - ch) // 2
    px = img.load()
    seen = {}

    def index(p):
        if p not in seen:
            seen[p] = nearest(p, pal)
        return seen[p]

    out = []
    for gy in range(ICON_H):
        ys = range(y0 + gy * ch // ICON_H, y0 + (gy + 1) * ch // ICON_H)
        for gx in range(ICON_W):
            xs = range(x0 + gx * cw // ICON_W, x0 + (gx + 1) * cw // ICON_W)
            votes = Counter(index(px[x, y]) for y in ys for x in xs)
            out.append(min(votes, key=lambda c: (-votes[c], c)))  # the most common color; ties to the lower index
    return out


def header(game, pal):
    data = pixels(ROOT / "games" / game / "art" / "launcher.png", pal)
    rows = ["  " + ",".join(str(v) for v in data[y * ICON_W : (y + 1) * ICON_W]) + "," for y in range(ICON_H)]
    return "\n".join(
        [
            f"// AUTO-GENERATED by tools/launcher_icons.py from games/{game}/art/launcher.png. Do not edit.",
            "// Include it from one .cpp only: the arrays have internal linkage.",
            "#pragma once",
            "#include <stdint.h>",
            '#include "gfx.h"',
            "static const uint8_t LAUNCHER_ICON_PX[] = {",
            *rows,
            "};",
            f"static const gfx::Sprite LAUNCHER_ICON = {{{ICON_W},{ICON_H},LAUNCHER_ICON_PX}};",
            "",
        ]
    )


def main():
    check = "--check" in sys.argv[1:]
    pal = palette()
    stale = []
    for game in GAMES:
        path, text = ROOT / "games" / game / "launcher_icon.h", header(game, pal)
        if not check:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
        elif not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(game)
    if stale:
        sys.exit(f"launcher icons out of date for {', '.join(stale)}: run tools/launcher_icons.py")
    if check:
        print("launcher icons up to date")


if __name__ == "__main__":
    main()
