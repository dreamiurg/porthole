#!/usr/bin/env python3
"""Regenerate bundled names/current rules/known transitions from pinned, public-domain IANA tzdb 2026b.

Source snapshot: tools/timezones/tzdata.zi, https://www.iana.org/time-zones .
Run python3 tools/timezones.py [--check]; requires the system zic compiler, no network or Python dependencies.
Only UTC 2024..2099 is supported. Known finite transitions take precedence over the recurring POSIX tail.
"""

import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import tempfile

APP = Path(__file__).resolve().parent.parent
SOURCE = APP / "tools/timezones/tzdata.zi"
OUTPUT = APP / "os/generated/timezones.h"
MIN_UTC = 1704067200
MAX_UTC = 4102444800
LABELS = {
    "America/Los_Angeles": "Pacific - Los Angeles",
    "America/New_York": "Eastern - New York",
    "America/Chicago": "Central - Chicago",
    "America/Denver": "Mountain - Denver",
    "America/Phoenix": "Arizona - Phoenix",
    "America/Anchorage": "Alaska - Anchorage",
    "Pacific/Honolulu": "Hawaii - Honolulu",
    "Europe/London": "London",
    "Etc/UTC": "UTC",
}


def tzif(raw):
    """Read the second TZif block's 64-bit transitions and offsets; ignore obsolete 32-bit/history sections."""
    gmt, standard, leaps, times, types, chars = struct.unpack(">6l", raw[20:44])
    second = 44 + times * 5 + types * 6 + chars + leaps * 8 + standard + gmt
    _, _, _, times, types, _ = struct.unpack(">6l", raw[second + 20 : second + 44])
    at = second + 44
    stamps = struct.unpack(">" + str(times) + "q", raw[at : at + times * 8])
    at += times * 8
    kinds = raw[at : at + times]
    at += times
    offsets = [struct.unpack(">lBB", raw[at + i * 6 : at + i * 6 + 6])[0] for i in range(types)]
    current = offsets[0]
    for stamp, kind in zip(stamps, kinds, strict=True):
        if stamp <= MIN_UTC:
            current = offsets[kind]
    known = [(MIN_UTC, current)]
    for stamp, kind in zip(stamps, kinds, strict=True):
        if MIN_UTC < stamp < MAX_UTC and offsets[kind] != known[-1][1]:
            known.append((stamp, offsets[kind]))
    # All current IANA transitions and offsets in this supported interval lie on a quarter-hour grid. Encode a
    # transition's elapsed quarter hours and signed offset in one uint32, preserving every known transition.
    encoded = []
    for stamp, seconds in known:
        if (stamp - MIN_UTC) % 900 or seconds % 900 or not -64 <= seconds // 900 < 64:
            raise ValueError("transition cannot be represented losslessly")
        encoded.append(((stamp - MIN_UTC) // 900 << 7) | (seconds // 900 + 64))
    through = min(MAX_UTC - 1, max(MIN_UTC, stamps[-1] if stamps else MIN_UTC))
    return raw.rsplit(b"\n", 2)[-2].decode("ascii"), tuple(encoded), through


def names(source):
    zones, links = [], {}
    for line in source.decode().splitlines():
        fields = line.split()
        if fields and fields[0] == "Z":
            zones.append(fields[1])
        if fields and fields[0] == "L":
            links[fields[2]] = fields[1]
    return sorted(zones), links


def canonical_aliases(zones, links):
    indices = {name: i for i, name in enumerate(zones)}
    aliases = []
    for alias, name in sorted(links.items()):
        while name in links:
            name = links[name]
        if name in indices:
            aliases.append((alias, indices[name]))
    return aliases


def deduplicate_ranges(ranges):
    unique_ranges, range_indices, range_ids = [], [], {}
    for value in ranges:
        if value not in range_ids:
            range_ids[value] = len(unique_ranges)
            unique_ranges.append(value)
        range_indices.append(range_ids[value])
    if len(unique_ranges) > 256:
        raise ValueError("range index overflow: update the generated index width")
    return unique_ranges, range_indices


def generate(tree, source):
    zones, links = names(source)
    items, transitions, ranges, dedup = [], [], [], {}
    for name in zones:
        rule, known, through = tzif((tree / name).read_bytes())
        if known not in dedup:
            dedup[known] = len(transitions)
            transitions.extend(known)
        if len(known) > 255 or dedup[known] > 65535:
            raise ValueError("transition range overflow")
        ranges.append((dedup[known], len(known), through))
        items.append((name, LABELS.get(name, name.rsplit("/", 1)[-1].replace("_", " ")), rule))
    aliases = canonical_aliases(zones, links)
    unique_ranges, range_indices = deduplicate_ranges(ranges)
    text = [
        "// Generated by tools/timezones.py from pinned public-domain IANA tzdb 2026b.",
        "// Known transitions from 2024 through 2099; recurring POSIX tails apply after each last known transition.",
        "// Source: tools/timezones/tzdata.zi, https://www.iana.org/time-zones .",
        "// tzdata.zi SHA256: " + hashlib.sha256(source).hexdigest(),
        "// Government rule changes require a firmware update; no runtime network dependency.",
        "#pragma once",
        "namespace timezones {",
        "static const Zone ZONES[] = {",
    ]
    text += ["  {" + ", ".join(json.dumps(value) for value in item) + "}," for item in items]
    text += [
        "};",
        "struct Alias { const char* id; uint16_t canonical; };  // unpacked: Apple ld rejects misaligned pointers",
        "static const Alias ALIASES[] = {",
    ]
    text += ["  {" + json.dumps(alias) + ", " + str(index) + "}," for alias, index in aliases]
    text += ["};", "static const uint32_t TRANSITIONS[] = {"]
    text += [f"  {encoded}u," for encoded in transitions]
    text += ["};", "struct __attribute__((packed)) KnownRange { uint16_t start; uint8_t count; uint32_t through; };", "static const KnownRange RANGES[] = {"]
    text += [f"  {{{start}, {count}, {through}u}}," for start, count, through in unique_ranges]
    text += ["};", "static const uint8_t RANGE_INDEX[] = {"]
    text += [f"  {index}," for index in range_indices]
    text += ["};", "}  // namespace timezones", ""]
    return "\n".join(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as directory:
        subprocess.run(["zic", "-b", "fat", "-d", directory, str(SOURCE)], check=True)
        rendered = generate(Path(directory), SOURCE.read_bytes())
    if args.check:
        if OUTPUT.read_text() != rendered:
            raise SystemExit("timezone catalog is stale: run python3 tools/timezones.py")
    else:
        OUTPUT.write_text(rendered)
    print("timezone catalog: IANA 2026b, 436 canonical names, 162 aliases, known transitions and recurring rules")


if __name__ == "__main__":
    main()
