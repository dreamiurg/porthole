#!/usr/bin/env python3
"""Kid news: news.toml -> shell/news_entries.h, and the PR checks on it.

  python3 tools/news.py            write shell/news_entries.h
  python3 tools/news.py --check    fail when it is out of date or news.toml breaks a rule (make lint)
  python3 tools/news.py pr --title T --body B --base OLD.toml --changed FILE...
                                   the PR's checks (.github/workflows/pr-title.yml): news.toml stays append-only, and a
                                   feat PR that changes the firmware adds an entry or says "none" under "## Kid news"

The rules for an entry are in AGENTS.md, "Kid news". The card's two-line fit is checked in C++ against the real font
(host/test_app_contract.cpp); this checks the rest.
"""

import argparse
import datetime
from pathlib import Path
import re
import sys
import tomllib

APP = Path(__file__).resolve().parent.parent
SOURCE = APP / "news.toml"
OUTPUT = APP / "shell/news_entries.h"
SIZES = {"new": "NEWS_NEW", "big": "NEWS_BIG", "game": "NEWS_GAME"}
FIELDS = {"date", "game", "size", "spot", "text", "gone"}
# Words a kid has no use for: what changed for them is the news, not how it was made.
BANNED = {"update", "updated", "version", "fix", "fixed", "bug", "bugs", "feature", "features", "improved", "faster", "settings", "beta", "wifi"}
EPOCH = datetime.date(1970, 1, 1)


def store_of(folder):
    """The game's NVS namespace (App::store()), which the shell matches entries by."""
    src = APP / "games" / folder / "game.h"
    if not src.exists():
        return None
    m = re.search(r'store\(\) const override \{ return "([a-z0-9]+)"', src.read_text())
    if m:
        return m.group(1)
    for f in sorted((APP / "games" / folder).glob("*.h")):
        m = re.search(r'constexpr const char\* STORE = "([a-z0-9]+)"', f.read_text())
        if m:
            return m.group(1)
    return None


def field_problems(e):
    """What is wrong with an entry's fields other than its text."""
    bad = [f"unknown field {k!r}" for k in sorted(set(e) - FIELDS)]
    try:
        datetime.date.fromisoformat(e.get("date", ""))
    except (TypeError, ValueError):
        bad.append("date is not YYYY-MM-DD")
    game, spot = e.get("game", ""), e.get("spot")
    if game != "porthole" and not store_of(game):
        bad.append(f"game {game!r} is not a folder under games/ with a store()")
    if e.get("size") not in SIZES:
        bad.append("size is not one of game, big, new")
    if spot is not None:
        calls = "".join(p.read_text() for p in (APP / "games" / game).glob("*.cpp")) if game != "porthole" else ""
        if not re.fullmatch(r"[a-z_]+", spot) or f'isNew("{spot}")' not in calls:
            bad.append(f'spot {spot!r}: games/{game}/ never calls news->isNew("{spot}")')
    if not isinstance(e.get("gone", False), bool):
        bad.append("gone is true or false")
    return bad


def text_problems(text):
    """What is wrong with a card's words, for a kid reading them alone."""
    if not text or not text.isascii() or not text.isprintable():
        return ["text is plain English letters (no emoji)"]
    words = {w.lower() for w in re.findall(r"[A-Za-z]+", text)}
    bad = [f"text says {w!r}: say what the kid can do instead" for w in sorted(words & BANNED)]
    if text.count("!") > 1:
        bad.append("text has more than one '!'")
    if re.search(r"\bv?\d+\.\d+|#\d+", text):
        bad.append("text has a version or a PR number")
    return bad


def problems(n, e):
    """What is wrong with entry number n (1-based), as messages."""
    bad = field_problems(e) + text_problems(e.get("text", ""))
    return [f"news.toml entry {n} ({e.get('game', '')}): {b}" for b in bad]


def load(path):
    with open(path, "rb") as f:
        return tomllib.load(f).get("news", [])


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(entries):
    rows = []
    for e in entries:
        day = (datetime.date.fromisoformat(e["date"]) - EPOCH).days
        store = "" if e["game"] == "porthole" else store_of(e["game"])
        rows.append(
            f"    {{{day}, shell::{SIZES[e['size']]}, {str(e.get('gone', False)).lower()}, {cstr(store)}, "
            f"{cstr(e.get('spot', ''))}, {cstr(e['text'])}}},   // {e['date']} {e['game']}"
        )
    return (
        "// Generated by tools/news.py from news.toml: do not edit. Entry k (1-based) is the k-th [[news]] there.\n"
        '#pragma once\n#include "news.h"\n\nnamespace shell {\n'
        "constexpr NewsEntry NEWS[] = {\n" + "\n".join(rows) + "\n};\n"
        "constexpr int NEWS_COUNT = sizeof NEWS / sizeof NEWS[0];\n}  // namespace shell\n"
    )


def same_entry(old, new):
    """An entry keeps what makes it the same news: its day, game, size and spot (text and gone may change)."""
    return all(old.get(k) == new.get(k) for k in ("date", "game", "size", "spot"))


def pr(args):
    bad = []
    entries = load(SOURCE)
    base = load(args.base) if args.base and Path(args.base).exists() else []
    if len(entries) < len(base) or not all(same_entry(o, n) for o, n in zip(base, entries, strict=False)):
        bad.append("news.toml is append-only: an entry's place is its number on every kid's device. Put old entries back as they were and add `gone = true` to take one back.")
    firmware = any(f.startswith("apps/porthole/") and not f.endswith(".md") and "/docs/" not in f for f in args.changed)
    touched = "apps/porthole/news.toml" in args.changed
    feat = re.match(r"feat(\([^)]*\))?!?: ", args.title or "")
    said_none = re.search(r"(?im)^##\s*Kid news\s*$\s*^\s*none\b", args.body or "")
    if feat and firmware and not touched and not said_none:
        bad.append('a feat PR that changes the firmware adds a news.toml entry, or says why not under "## Kid news" ("none: <why>"). The rules: "Kid news" in AGENTS.md.')
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", nargs="?", choices=["pr"])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--title")
    ap.add_argument("--body")
    ap.add_argument("--base")
    ap.add_argument("--changed", nargs="*", default=[])
    args = ap.parse_args()
    if args.mode == "pr":
        bad = pr(args)
    else:
        entries = load(SOURCE)
        bad = [p for n, e in enumerate(entries, 1) for p in problems(n, e)]
        if not bad:
            out = render(entries)
            if args.check and (not OUTPUT.exists() or OUTPUT.read_text() != out):
                bad.append(f"{OUTPUT.relative_to(APP)} is out of date: run python3 tools/news.py")
            elif not args.check:
                OUTPUT.write_text(out)
    for b in bad:
        print(b, file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
