#!/usr/bin/env python3
"""Pumpkin's raster assets: GPT images in art/*.png -> headers on the 160px grid and palette.

Each PNG came from Codex's built-in image generator and was approved by eye on the real screen.
Every prompt asked for retro 16-bit pixel art, large square pixels, a chunky #201d32 outline,
no anti-aliasing, no text and a flat #00FF00 background, in Pumpkin's palette.
  pie.png (YOU LOST): a whole pumpkin pie whose filling shows a goofy jack-o'-lantern face
    pressed in darker rust, a little green stem on top, golden crust. Funny, not scary.
  ghost.png (the window ghost): a little round ghost with a scalloped bottom edge, big happy
    eyes, rosy cheeks, one small arm waving hello; bold shapes in cream, ink, pink-lilac, sky
    and purple.

Each grid cell takes the most common palette colour among its source pixels (green counts as
transparent), then a 1px ink rim keeps the art off whatever is behind it. Saturated greens read
as the key, so a replacement image should keep its greens muted (sage, olive). Needs Pillow.
  python3 games/pumpkin-hide-seek/tools/gpt_art.py           regenerate every header
  python3 games/pumpkin-hide-seek/tools/gpt_art.py --check   fail if any header is stale

Not art.py: mypy names modules in hyphenated game dirs by file name alone, so it would clash with Pets Club's.
"""

import sys
from collections import Counter
from functools import cache
from pathlib import Path

from PIL import Image

GAME = Path(__file__).resolve().parents[1]
INK = 0x201D32
# render.cpp's palette, minus the beam and sky colours
BASE = (0x201D32, 0x463451, 0x815573, 0xB9809A, 0x925743, 0x633E43, 0xF58B32, 0xB74F30, 0xFFC875, 0xFFEDC2, 0x87A878, 0x49674D, 0x263449, 0x53637A, 0xE6B79D, 0xB6ACB4)
SKY = 0x9AD4E4
# (source, box w, box h, palette, header, namespace); the box excludes the 1px rim
ASSETS = (
    ("pie.png", 112, 54, BASE, "pie.h", "pie"),  # fits between the YOU LOST plate and the button
    ("ghost.png", 20, 20, (*BASE, SKY), "ghost.h", "ghost"),  # inside its tap box {22,30,24,24}
)
CLEAR, RIM = -1, -2


def rgb(c):
    return (c >> 16) & 255, (c >> 8) & 255, c & 255


def keyed(p):
    return p[1] > p[0] + 60 and p[1] > p[2] + 60  # the green screen and its fringes


@cache  # the art has far fewer distinct colours than pixels
def nearest(p, palette):
    return min(palette, key=lambda c: sum((a - b) ** 2 for a, b in zip(p, rgb(c), strict=True)))


def cells(image, box_w, box_h, palette):
    px = image.load()
    mask = Image.new("L", image.size)
    mp = mask.load()
    for y in range(image.height):
        for x in range(image.width):
            mp[x, y] = 0 if keyed(px[x, y]) else 255
    x0, y0, x1, y1 = mask.getbbox()
    scale = min(box_w / (x1 - x0), box_h / (y1 - y0))
    w, h = round((x1 - x0) * scale), round((y1 - y0) * scale)

    def span(origin, cell, limit):  # at least one source pixel per cell, even when upscaling
        start = min(limit - 1, origin + int(cell / scale))
        return range(start, max(start + 1, min(limit, origin + int((cell + 1) / scale))), 2)

    def vote(gx, gy):
        xs = span(x0, gx, x1)
        ys = span(y0, gy, y1)
        votes = Counter(CLEAR if keyed(px[x, y]) else nearest(px[x, y], palette) for y in ys for x in xs)
        return votes.most_common(1)[0][0]

    return [[vote(gx, gy) for gx in range(w)] for gy in range(h)]


def rimmed(grid):
    w, h = len(grid[0]) + 2, len(grid) + 2
    out = [[CLEAR] * w for _ in range(h)]
    for y, row in enumerate(grid):
        out[y + 1][1 : w - 1] = row

    def solid(x, y):
        return 0 <= x < w and 0 <= y < h and out[y][x] >= 0

    for y in range(h):
        for x in range(w):
            if out[y][x] == CLEAR and any(solid(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out[y][x] = RIM
    return [[INK if c == RIM else c for c in row] for row in out]


def header(source, box_w, box_h, palette, name):
    grid = rimmed(cells(Image.open(GAME / "art" / source).convert("RGB"), box_w, box_h, palette))
    colours = sorted({c for row in grid for c in row if c != CLEAR})
    index = {c: i for i, c in enumerate(colours)}
    data = ",".join(str(255 if c == CLEAR else index[c]) for row in grid for c in row)
    return "\n".join(
        [
            f"// Generated by games/pumpkin-hide-seek/tools/gpt_art.py from art/{source}. Do not edit.",
            "#pragma once",
            "#include <stdint.h>",
            f"namespace pumpkin {{ namespace {name} {{",
            f"constexpr int W = {len(grid[0])}, H = {len(grid)};",
            "constexpr uint32_t COLORS[] = {" + ",".join(f"0x{c:06x}" for c in colours) + "};",
            "constexpr uint8_t CLEAR = 255;",
            f"constexpr uint8_t PX[] = {{{data}}};",
            f"}} }}  // namespace pumpkin::{name}",
            "",
        ]
    )


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for source, box_w, box_h, palette, out, name in ASSETS:
        text, path = header(source, box_w, box_h, palette, name), GAME / out
        if not check:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(GAME.parents[1])}")
        elif not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(out)
    if stale:
        print(f"{', '.join(stale)} out of date: run `make art`")
        sys.exit(1)
    if check:
        print("art headers up to date")


if __name__ == "__main__":
    main()
