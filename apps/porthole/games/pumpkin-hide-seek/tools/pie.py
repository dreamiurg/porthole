#!/usr/bin/env python3
"""The YOU LOST pie: art/pie.png (a GPT image) -> pie.h on Pumpkin's 160px grid and palette.

art/pie.png came from Codex's built-in image generator, approved by eye on the real lost screen. Prompt:
  retro 16-bit pixel art, large square pixels, chunky #201d32 outline, no anti-aliasing, no text,
  flat #00FF00 background, Pumpkin's palette; a whole pumpkin pie whose filling shows a goofy
  jack-o'-lantern face pressed in darker rust, a little green stem on top, golden crust. Funny, not scary.

Each grid cell takes the most common palette colour among its source pixels (green counts as
transparent), then a 1px ink rim keeps the pie off the orange page. Needs Pillow.
  python3 games/pumpkin-hide-seek/tools/pie.py           regenerate pie.h
  python3 games/pumpkin-hide-seek/tools/pie.py --check   fail if pie.h is stale
"""

import sys
from collections import Counter
from pathlib import Path

from PIL import Image

GAME = Path(__file__).resolve().parents[1]
SOURCE, HEADER = GAME / "art/pie.png", GAME / "pie.h"
BOX_W, BOX_H = 112, 54  # fits between the YOU LOST plate and the button
INK = 0x201D32
# render.cpp's palette, minus the beam and sky colours a pie never needs
PALETTE = (0x201D32, 0x463451, 0x815573, 0xB9809A, 0x925743, 0x633E43, 0xF58B32, 0xB74F30, 0xFFC875, 0xFFEDC2, 0x87A878, 0x49674D, 0x263449, 0x53637A, 0xE6B79D, 0xB6ACB4)
CLEAR, RIM = -1, -2


def rgb(c):
    return (c >> 16) & 255, (c >> 8) & 255, c & 255


def keyed(p):
    return p[1] > p[0] + 60 and p[1] > p[2] + 60  # the green screen and its fringes


def nearest(p):
    return min(PALETTE, key=lambda c: sum((a - b) ** 2 for a, b in zip(p, rgb(c), strict=True)))


def cells(image):
    px = image.load()
    mask = Image.new("L", image.size)
    mp = mask.load()
    for y in range(image.height):
        for x in range(image.width):
            mp[x, y] = 0 if keyed(px[x, y]) else 255
    x0, y0, x1, y1 = mask.getbbox()
    scale = min(BOX_W / (x1 - x0), BOX_H / (y1 - y0))
    w, h = round((x1 - x0) * scale), round((y1 - y0) * scale)

    def vote(gx, gy):
        xs = range(x0 + int(gx / scale), min(x1, x0 + int((gx + 1) / scale)), 2)
        ys = range(y0 + int(gy / scale), min(y1, y0 + int((gy + 1) / scale)), 2)
        votes = Counter(CLEAR if keyed(px[x, y]) else nearest(px[x, y]) for y in ys for x in xs)
        return votes.most_common(1)[0][0]

    return [[vote(gx, gy) for gx in range(w)] for gy in range(h)]


def rimmed(grid):
    w, h = len(grid[0]) + 2, len(grid) + 2
    out = [[CLEAR] * w for _ in range(h)]
    for y, row in enumerate(grid):
        out[y + 1][1 : w - 1] = row

    def solid(x, y):
        return 0 <= x < w and 0 <= y < h and out[y][x] >= 0

    for y in range(h):
        for x in range(w):
            if out[y][x] == CLEAR and any(solid(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out[y][x] = RIM
    return [[INK if c == RIM else c for c in row] for row in out]


def header():
    grid = rimmed(cells(Image.open(SOURCE).convert("RGB")))
    colours = sorted({c for row in grid for c in row if c != CLEAR})
    index = {c: i for i, c in enumerate(colours)}
    data = ",".join(str(255 if c == CLEAR else index[c]) for row in grid for c in row)
    return "\n".join(
        [
            "// Generated by games/pumpkin-hide-seek/tools/pie.py from art/pie.png. Do not edit.",
            "#pragma once",
            "#include <stdint.h>",
            "namespace pumpkin { namespace pie {",
            f"constexpr int W = {len(grid[0])}, H = {len(grid)};",
            "constexpr uint32_t COLORS[] = {" + ",".join(f"0x{c:06x}" for c in colours) + "};",
            "constexpr uint8_t CLEAR = 255;",
            f"constexpr uint8_t PX[] = {{{data}}};",
            "} }  // namespace pumpkin::pie",
            "",
        ]
    )


def main():
    text = header()
    if "--check" in sys.argv[1:]:
        if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != text:
            print("pie.h is out of date: run `make art`")
            sys.exit(1)
        print("pie.h up to date")
        return
    HEADER.write_text(text, encoding="utf-8")
    print(f"wrote {HEADER.relative_to(GAME.parents[1])}")


if __name__ == "__main__":
    main()
