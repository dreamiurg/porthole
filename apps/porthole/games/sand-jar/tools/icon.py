def sprite():
    im = ascii_img(ICON)
    assert im.w == 32 and im.h == 32, "the launcher slot fits a 32x32 icon"
    im.outline(K)
    return im


def emit(check=False):
    im = sprite()
    text = "\n".join(
        [
            "// AUTO-GENERATED by games/sand-jar/tools/icon.py. Edit the generator, not this file.",
            "#pragma once",
            '#include "gfx.h"',
            "namespace sandjar {",
            f"static const uint8_t sandjar_icon_px[] = {{{','.join(str(c) for row in im.px for c in row)}}};",
            f"static const gfx::Sprite SPR_SANDJAR_ICON = {{{im.w},{im.h},sandjar_icon_px}};",
            "}  // namespace sandjar",
        ]
    )
    text += "\n"
    if check:
        current = Path(HEADER).read_text(encoding="utf-8") if Path(HEADER).exists() else ""
        if current != text:
            print(f"{HEADER} is out of date: run `python3 games/sand-jar/tools/icon.py`")
            sys.exit(1)
        print(f"{HEADER} up to date")
        return
    Path(HEADER).write_text(text, encoding="utf-8")
    print(f"wrote {HEADER}")
    preview(im)


def preview(im):
    try:
        from PIL import Image
    except ImportError:
        print("Pillow missing; skipping preview")
        return
    src = Path("os/palette.h").read_text(encoding="utf-8")
    pal = [int(h, 16) for h in re.findall(r"0x[0-9A-Fa-f]{6}", src[src.index("PALETTE_RGB") :])[:32]]
    z = 12
    img = Image.new("RGB", (im.w * z, im.h * z), (255, 255, 255))
    for y in range(im.h):
        for x in range(im.w):
            c = im.px[y][x]
            if c != T:
                rgb = pal[c]
                img.paste(((rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255), (x * z, y * z, x * z + z, y * z + z))
    os.makedirs(os.path.dirname(PREVIEW), exist_ok=True)
    img.save(PREVIEW)
    print(f"wrote {PREVIEW}")


if __name__ == "__main__":
    os.chdir(os.path.dirname(os.path.abspath(__file__)) + "/../../..")
    emit(check="--check" in sys.argv)
