#!/usr/bin/env python3
"""Validate the authored chapter and produce compact, static C++ tables."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KINDS = {
    key: key.title()
    for key in (
        "fact",
        "item",
        "quest",
        "skill",
        "relation",
        "promise",
        "decision",
        "day",
        "variant",
        "outcome",
        "seen",
        "event",
        "all",
        "any",
        "schedule",
        "location",
        "deed",
    )
}
REGISTRIES = {"fact": "facts", "item": "items", "quest": "quests", "skill": "skills", "relation": "npcs", "promise": "promises", "event": "events", "schedule": "events"}
LIMITS = {"facts": 64, "items": 16, "quests": 16, "skills": 3, "npcs": 16, "promises": 16, "events": 8}
LOCATIONS = ["village", "bridge", "mill", "woods", "marsh", "tower"]
STATES = {"undiscovered": 0, "available": 1, "active": 2, "blocked": 3, "deferred": 4, "resolved": 5, "none": 0, "open": 1, "kept": 2, "broken": 3}
COMPARISONS = {"eq", "ne", "ge", "le"}
PREDICATES = set(REGISTRIES) - {"schedule"} | {"decision", "day", "variant", "outcome", "seen"}
EFFECTS = {"fact", "item", "quest", "skill", "relation", "promise", "day", "schedule", "outcome", "location", "deed"}


def bounded(value, minimum, maximum, label):
    if not isinstance(value, int) or not minimum <= value <= maximum:
        raise ValueError(f"{label} must be {minimum}..{maximum}")
    return value


def rule_value(rule):
    value = rule.get("value", 0 if rule["kind"] == "location" else 1)
    return STATES.get(value, value) if isinstance(value, str) else value


def validate_value(kind, value, identity, effect=False):
    ranges = {
        "fact": (0, 1),
        "item": (0, 99),
        "quest": (0, 5),
        "skill": (0, 6),
        "relation": (-5, 5),
        "promise": (0, 3),
        "day": (1, 65535),
        "outcome": (0, 4),
        "seen": (0, 1),
        "decision": (0, 1),
        "event": (0, 1),
        "variant": (0, 2 if identity == 3 else 1),
    }
    if effect:
        ranges.update(item=(-99, 99), skill=(-6, 6), relation=(-10, 10), day=(0, 65535), schedule=(1, 65535), deed=(0, 8), location=(0, 0))
    minimum, maximum = ranges[kind]
    return bounded(value, minimum, maximum, f"{kind} value")


def quote(value):
    """Only printable ASCII and explicit paragraph breaks enter the custom font."""
    if any(ord(char) > 126 or ord(char) < 32 and char != "\n" for char in value):
        raise ValueError(f"unsupported glyph in {value!r}")
    return json.dumps(value, ensure_ascii=True)


def key(entry):
    return entry if isinstance(entry, str) else entry.get("slug", entry.get("key", entry.get("id")))


def validate_lock(previous, current):
    for registry, entries in previous.items():
        if any(current.get(registry, {}).get(identity) != value for identity, value in entries.items()):
            raise ValueError(f"persisted {registry} identities changed")


class Compiler:
    def __init__(self, data):
        self.data = data
        self.lines = ["// Generated by tools/content.py; edit content/chapter-01.json."]
        self.serial = 0
        self.maps = {}
        for name, limit in LIMITS.items():
            entries = data.get(name, [])
            keys = [key(entry) for entry in entries]
            if len(keys) != len(set(keys)) or len(keys) > limit:
                raise ValueError(f"duplicate or too many {name}")
            self.maps[name] = {entry: i + (name == "items") for i, entry in enumerate(keys)}
        self.maps["scenes"] = {key(s): s["id"] for s in data["scenes"]}
        self.maps["choices"] = {key(c): c["id"] for s in data["scenes"] for c in s["choices"]}
        self.maps["choice_slots"] = {f"{key(s)}:{index}": c["id"] for s in data["scenes"] for index, c in enumerate(s["choices"])}

    def identity(self, kind, identity):
        numeric = type(identity) is int or isinstance(identity, str) and identity.isdigit()
        if kind == "location":
            return bounded(int(identity), 0, 5, "location id") if numeric else LOCATIONS.index(identity)
        table = REGISTRIES.get(kind, {"seen": "scenes", "decision": "choices"}.get(kind))
        if table:
            value = int(identity) if numeric else self.maps[table].get(identity, -1)
            if value not in self.maps[table].values():
                raise ValueError(f"unknown {kind} id {identity!r}")
            return value
        if kind == "variant":
            return bounded(int(identity), 0, 3, "variant id")
        if identity not in (0, "", "0"):
            raise ValueError(f"{kind} does not use an id")
        return 0

    def array(self, typename, entries):
        if not entries:
            return "nullptr"
        self.serial += 1
        name = f"data_{self.serial}"
        self.lines.append(f"static const {typename} {name}[] = {{\n" + ",\n".join(entries) + "\n};")
        return name

    def condition(self, rule):
        group = next((name for name in ("all", "any") if name in rule), None)
        if group:
            children = [self.condition(child) for child in rule[group]]
            name = self.array("Condition", children)
            return "{{Kind::{},0,0,Compare::Eq,{},{},{}}}".format(KINDS[group], name, len(children), quote(rule.get("reason", "More evidence is needed.")))
        kind = rule["kind"]
        if kind not in PREDICATES:
            raise ValueError(f"unsupported predicate {kind}")
        identity = self.identity(kind, rule.get("id", 0))
        value = validate_value(kind, rule_value(rule), identity)
        compare = rule.get("op", "ge" if kind in ("item", "skill", "day", "relation") else "eq")
        if compare not in COMPARISONS:
            raise ValueError(f"unknown comparison {compare}")
        reason = rule.get("reason", self.reason(kind, rule.get("id", 0), value))
        return f"{{Kind::{KINDS[kind]},{identity},{value},Compare::{compare.title()},nullptr,0,{quote(reason)}}}"

    def reason(self, kind, identity, value):
        if kind in ("fact", "seen", "decision"):
            return "Investigate further to understand this option."
        if kind == "item":
            name = self.data["items"][self.identity(kind, identity) - 1]["name"]
            return f"Needs {value} {name.lower()}."
        if kind == "skill":
            name = self.data["skills"][self.identity(kind, identity)]["name"]
            return f"Needs {name} {value}."
        if kind == "promise":
            return "A promise must be settled first."
        return "This opportunity is not ready yet."

    def requires(self, rules):
        entries = [self.condition(rule) for rule in rules]
        return "{{{},{}}}".format(self.array("Condition", entries), len(entries))

    def effects(self, rules):
        entries = []
        for rule in rules:
            kind = rule["kind"]
            if kind not in EFFECTS:
                raise ValueError(f"unsupported effect {kind}")
            identity = self.identity(kind, rule.get("id", 0))
            value = validate_value(kind, rule_value(rule), identity, effect=True)
            variant = int(rule.get("variant", -1))
            if variant < -1 or variant > 3:
                raise ValueError("effect variant index must be -1..3")
            if variant >= 0 and kind not in ("day", "schedule"):
                raise ValueError("seeded effect values support day and schedule")
            entries.append(f"{{Kind::{KINDS[kind]},{identity},{value},{variant}}}")
        return "{{{},{}}}".format(self.array("Effect", entries), len(entries))

    def choice(self, choice):
        strings = [
            key(choice),
            choice["caption"],
            choice.get("detail", ""),
            choice.get("journal", choice["caption"]),
            choice.get("result", choice.get("journal", choice["caption"])),
        ]
        return "{{{},{},{},{},{},{}}}".format(
            choice["id"],
            ",".join(map(quote, strings)),
            self.requires(choice.get("requires", [])),
            self.effects(choice.get("effects", [])),
            choice.get("next", 0),
            str(choice.get("confirm", False)).lower(),
        )

    def scene(self, scene):
        requirements = self.requires(scene.get("requires", []))
        paragraphs = self.array("char* const", [quote(p) for p in scene["paragraphs"]])
        choices = self.array("Choice", [self.choice(c) for c in scene["choices"]])
        return "{{{},{},{},{},{},{},{},{},{},{},{},{}}}".format(
            scene["id"],
            quote(key(scene)),
            quote(scene["title"]),
            LOCATIONS[LOCATIONS.index(scene["location"])].upper(),
            scene.get("priority", 0),
            str(scene.get("once", True)).lower(),
            scene.get("cooldown", 1),
            requirements,
            paragraphs,
            len(scene["paragraphs"]),
            choices,
            len(scene["choices"]),
        )

    def named(self, registry):
        entries = []
        for entry in self.data.get(registry, []):
            row = {"id": entry} if isinstance(entry, str) else entry
            identity = key(row)
            entries.append("{{{},{},{}}}".format(quote(identity), quote(row.get("name", identity)), quote(row.get("description", identity))))
        return self.array("Named", entries)

    def quests(self):
        entries = []
        for quest in self.data["quests"]:
            objectives = quest.get("objectives", {})
            texts = [objectives.get(state, quest["name"]) for state in list(STATES)[:6]]
            entries.append("{{{},{},{{{}}}}}".format(quote(key(quest)), quote(quest["name"]), ",".join(map(quote, texts))))
        return self.array("Quest", entries)

    def compile(self):
        scenes = self.array("Scene", [self.scene(scene) for scene in self.data["scenes"]])
        rows = [f"{scenes},{len(self.data['scenes'])}"]
        for registry in ("facts", "items", "skills", "npcs", "promises"):
            rows.append(f"{self.named(registry)},{len(self.data.get(registry, []))}")
        rows.append(f"{self.quests()},{len(self.data['quests'])}")
        events = ["{{{},{},{}}}".format(quote(key(e)), quote(e["description"]), self.effects(e["effects"])) for e in self.data.get("events", [])]
        rows.append(f"{self.array('Event', events)},{len(events)}")
        self.lines.append("static const Content CHAPTER = {\n" + ",\n".join(rows) + "\n};")
        return "\n\n".join(self.lines) + "\n"


def validate_ids(entries, maximum):
    values = [entry["id"] for entry in entries]
    if len(values) != len(set(values)) or any(type(v) is not int or v <= 0 or v >= maximum for v in values):
        raise ValueError("duplicate or out-of-range numeric ids")
    keys = [key(entry) for entry in entries]
    if len(keys) != len(set(keys)):
        raise ValueError("duplicate stable key")


def validate_scenes(scenes):
    for scene in scenes:
        if not scene["choices"] or len(scene["choices"]) > 8:
            raise ValueError(f"scene {scene['id']} needs 1..8 choices")
        if len("\n\n".join(scene["paragraphs"])) >= 8192:
            raise ValueError(f"scene {scene['id']} exceeds reader buffer")


def validate(data):
    scenes = data["scenes"]
    scene_ids = [s["id"] for s in scenes]
    choices = [c for s in scenes for c in s["choices"]]
    validate_ids(scenes, 128)
    validate_ids(choices, 512)
    validate_scenes(scenes)
    if {s["location"] for s in scenes} != set(LOCATIONS):
        raise ValueError("all six locations must have narrative content")
    for choice in choices:
        if choice.get("next", 0) not in [0, *scene_ids]:
            raise ValueError(f"broken next at {key(choice)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads((ROOT / "content/chapter-01.json").read_text())
    validate(data)
    compiler = Compiler(data)
    generated = compiler.compile()
    target = ROOT / "generated/content.inc"
    lock = ROOT / "content/ids.json"
    identities = json.dumps(compiler.maps, indent=2) + "\n"
    if lock.exists():
        old = json.loads(lock.read_text())
        validate_lock(old, compiler.maps)
    if args.check:
        if not target.exists() or target.read_text() != generated or lock.read_text() != identities:
            raise SystemExit("Kingdom generated content is stale; run tools/content.py")
    else:
        target.write_text(generated)
        lock.write_text(identities)
    print(f"Kingdom content: {len(data['scenes'])} scenes, validated stable graph")


if __name__ == "__main__":
    main()
