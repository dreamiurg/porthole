#!/usr/bin/env python3
"""Rally's text: Russo One (SIL OFL 1.1, art/fonts/) rasterized to the runtime's 4 bpp font format (os/font.h).

Four sizes, ASCII 32..126, no kerning. FreeType's output can change between Pillow releases, so the header records
the font file's SHA-256 and the Pillow it was made with: --check always fails on a changed font file, and also
re-renders and compares byte for byte when this Pillow is that one.
  python3 games/racing/tools/font.py           regenerate fonts.h (with the pinned Pillow)
  python3 games/racing/tools/font.py --check   fail if fonts.h is stale
"""

import hashlib
import re
import sys
from pathlib import Path

from PIL import Image, ImageFont
from PIL import __version__ as PILLOW

GAME = Path(__file__).resolve().parents[1]
TTF = GAME / "art/fonts/RussoOne-Regular.ttf"
OUT = GAME / "fonts.h"
PINNED = "12.3.0"
SIZES = (("SMALL", 22), ("LABEL", 28), ("BIG", 44), ("GIANT", 64))  # px: body text, buttons, HUD numbers, countdown


def pack4(values):
    out = []
    for i in range(0, len(values), 2):
        hi = values[i]
        lo = values[i + 1] if i + 1 < len(values) else 0
        out.append(hi << 4 | lo)
    return out


def rows(kind, name, values):
    body = ["  " + ",".join(map(str, values[i : i + 32])) + "," for i in range(0, len(values), 32)]
    return [f"static const {kind} {name}[] = {{", *body, "};"]


def face_lines(name, size):
    face = ImageFont.truetype(str(TTF), size, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = face.getmetrics()
    bitmap, glyphs = [], [(0, 0, 0, 0, 0, 0)]
    for code in range(32, 127):
        mask, offset = face.getmask2(chr(code), mode="L", anchor="ls")
        image = Image.frombytes("L", mask.size, bytes(mask))
        box = image.getbbox()
        adv = round(face.getlength(chr(code)) * 16)
        if not box:
            glyphs.append((len(bitmap), adv, 0, 0, 0, 0))
            continue
        image = image.crop(box)
        left, top = offset[0] + box[0], offset[1] + box[1]
        glyphs.append((len(bitmap), adv, image.width, image.height, left, -top - image.height))
        # each glyph starts on a byte: os/font.cpp reads its rows from bitmapIndex, high nibble first
        bitmap.extend(pack4([(v * 15 + 127) // 255 for v in image.tobytes()]))
    out = rows("uint8_t", f"{name}_BITMAP", bitmap) + [f"static const font::Glyph {name}_GLYPHS[] = {{"]
    out += ["  {" + ",".join(map(str, g)) + "}," for g in glyphs]
    out += ["};", f"inline const font::Font {name} = {{{name}_BITMAP,{name}_GLYPHS,nullptr,0,NO_CLASS,NO_CLASS,NO_KERN,0,{ascent + descent},{descent}}};"]
    return out


def header():
    digest = hashlib.sha256(TTF.read_bytes()).hexdigest()
    lines = [
        "// AUTO-GENERATED by tools/font.py from art/fonts/RussoOne-Regular.ttf (SIL OFL 1.1). Do not edit.",
        f"// source sha256 {digest}, Pillow {PILLOW}",
        "#pragma once",
        '#include "font.h"',
        "namespace racing::fonts {",
        *rows("uint8_t", "NO_CLASS", [0] * 96),
        "static const int8_t NO_KERN[] = {0};",
    ]
    for name, size in SIZES:
        lines += face_lines(name, size)
    return "\n".join([*lines, "}  // namespace racing::fonts", ""])


def main():
    if "--check" not in sys.argv[1:]:
        if PILLOW != PINNED:
            sys.exit(f"font.py renders with Pillow=={PINNED} (this is {PILLOW}): uv run --with pillow=={PINNED} ...")
        OUT.write_text(header(), encoding="utf-8")
        print(f"wrote {OUT.relative_to(GAME.parents[1])}")
        return
    text = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    m = re.search(r"source sha256 (\w+), Pillow (\S+)", text)
    if not m or m[1] != hashlib.sha256(TTF.read_bytes()).hexdigest():
        sys.exit("fonts.h is stale for art/fonts/RussoOne-Regular.ttf: run games/racing/tools/font.py")
    if PILLOW == m[2] and header() != text:
        sys.exit("fonts.h differs from a fresh render: run games/racing/tools/font.py")
    print("racing fonts up to date")


if __name__ == "__main__":
    main()
