for a, b in ((")", "("), (">", "<"), ("\\", "/"), ("]", "["), ("}", "{")):
    GLYPHS[a] = (GLYPHS[b][0], [r[::-1] for r in GLYPHS[b][1]])


def slant(y):
    return 2 if y <= 2 else 1 if y <= 5 else 0


def glyph(ch):
    start, rows = GLYPHS[ch]
    w = max(slant(start + i) + len(r) for i, r in enumerate(rows))
    bits = [0] * 10
    for i, r in enumerate(rows):
        y = start + i
        line = "." * slant(y) + r
        bits[y] = int(line.ljust(w, ".").replace("#", "1").replace(".", "0"), 2)
    return w, bits


