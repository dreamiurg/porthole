def header():
    font = [glyph(chr(c)) for c in range(32, 127)]
    assert len(font) == 95 and all(0 < w <= 16 for w, _ in font)
    lines = [
        "// AUTO-GENERATED by tools/art.py. Edit the generator, never this file.",
        "#pragma once",
        "#include <stdint.h>",
        "namespace racing::art {",
        "struct Glyph { uint8_t w; uint16_t rows[10]; };",
        "struct Theme { uint32_t skyTop, skyLow, grassA, grassB, rumbleA, rumbleB, roadA, roadB, lane, hazard, hazardEdge, ice, iceEdge; };",
        "inline constexpr Theme THEME[4] = {",
        *("  {" + ",".join(f"0x{c:06X}" for c in t) + "}," for t in THEMES),
        "};",
        "inline constexpr Glyph FONT[95] = {",
        *(f"  {{{w},{{{','.join(f'0x{r:04X}' for r in rows)}}}}},  // {chr(32 + i)!r}" for i, (w, rows) in enumerate(font)),
        "};",
        "}  // namespace racing::art\n",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    out = ROOT / "assets.h"
    data = header()
    if args.check:
        if not out.exists() or out.read_text() != data:
            raise SystemExit("Racing assets stale: run games/racing/tools/art.py")
        print("Racing art matches generator.")
        return
    out.write_text(data)
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
