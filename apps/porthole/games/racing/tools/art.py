#!/usr/bin/env python3
"""Rally's road colors. Reproduce assets.h; --check never writes.

The pictures (cars, pickups, scenery, skylines) are Codex images converted by tools/pictures.py.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


THEMES = [  # skyTop, skyLow, grassA, grassB, rumbleA, rumbleB, roadA, roadB, lane, hazard, hazardEdge, ice, iceEdge
    (0x2E7FD8, 0x9CD4F0, 0xE2B464, 0xD09A4E, 0xC0482A, 0xF2E2C4, 0x7A6A5E, 0x726256, 0xF6D040, 0x6A4226, 0x3E2414, 0xBDF0FF, 0x5AA8D0),
    (0x5A2440, 0xFFA040, 0x5A2E1E, 0x4A2418, 0xFF8A1E, 0x1A1418, 0x3E3A3E, 0x383438, 0xF0C040, 0x0C0A10, 0x7A5AB0, 0xBDF0FF, 0x5AA8D0),
    (0x4A8ADA, 0xD8ECFF, 0xF4F8FF, 0xD6E4F4, 0xD82828, 0xFFFFFF, 0x363A48, 0x313542, 0xF4F8FF, 0x8A8C96, 0x5A5E6A, 0xBDF4FF, 0x4AA6D2),
    (0x0C0828, 0x4A2482, 0x343E5E, 0x2C3552, 0xFF3CAA, 0x30E0F0, 0x1E1A3E, 0x1A1636, 0xC8F0FF, 0x1A6A76, 0x5AE0E8, 0xBDF0FF, 0x5AA8D0),
]


def header():
    lines = [
        "// AUTO-GENERATED by tools/art.py. Edit the generator, never this file.",
        "#pragma once",
        "#include <stdint.h>",
        "namespace racing::art {",
        "struct Theme { uint32_t skyTop, skyLow, grassA, grassB, rumbleA, rumbleB, roadA, roadB, lane, hazard, hazardEdge, ice, iceEdge; };",
        "inline constexpr Theme THEME[4] = {",
        *("  {" + ",".join(f"0x{c:06X}" for c in t) + "}," for t in THEMES),
        "};",
        "}  // namespace racing::art\n",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    out = ROOT / "assets.h"
    data = header()
    if args.check:
        if not out.exists() or out.read_text() != data:
            raise SystemExit("Racing assets stale: run games/racing/tools/art.py")
        print("Racing art matches generator.")
        return
    out.write_text(data)
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
