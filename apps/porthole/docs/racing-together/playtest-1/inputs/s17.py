from duo import *
import sys

mode = sys.argv[1]
a, b = start()
to_race(a, b)
both(a, b, 12000)
if mode == "holds":
    for i in range(1, 4):
        a.do("hold 42 40")
        both(a, b, 600)
        a.snap(f"24_hold{i}")
        b.snap(f"24_hold{i}")
        if a.screen == "race_pause":
            a.tap(80, 48)
            both(a, b, 300)
            a.snap(f"24_resume{i}_0")
            b.snap(f"24_resume{i}_0")
            both(a, b, 2500)
            a.snap(f"24_resume{i}_3s")
            b.snap(f"24_resume{i}_3s")
    # B pauses while A out of holds
    b.do("hold 42 40")
    both(a, b, 600)
    a.snap("24_b_hold")
    b.snap("24_b_hold")
    b.tap(80, 48)
    both(a, b, 3000)
    b.do("hold 42 40")
    both(a, b, 600)
    b.tap(80, 48)
    both(a, b, 3000)
    b.do("hold 42 40")
    both(a, b, 600)
    a.snap("24_b_hold3")
    b.snap("24_b_hold3")
elif mode == "tracks":
    a.do("hold 42 40")
    both(a, b, 600)
    a.tap(52, 108)
    both(a, b, 1500)
    a.snap("25_a_tracks_from_pause")
    b.snap("25_a_tracks_from_pause")
    both(a, b, 5000)
    a.snap("25_5s")
    b.snap("25_5s")
elif mode == "home":
    a.do("hold 42 40")
    both(a, b, 600)
    a.tap(108, 108)
    both(a, b, 1500)
    a.snap("26_a_home_from_pause")
    b.snap("26_a_home_from_pause")
    both(a, b, 5000)
    a.snap("26_5s")
    b.snap("26_5s")
elif mode == "newgrip":
    a.do("hold 42 40")
    both(a, b, 600)
    a.tap(52, 78)
    both(a, b, 1500)
    a.snap("27_newgrip")
    b.snap("27_newgrip")
    both(a, b, 4000)
    a.snap("27_newgrip_4s")
    b.snap("27_newgrip_4s")
    a.tap(106, 124)
    both(a, b, 2000)
    a.snap("27_newgrip_go")
    b.snap("27_newgrip_go")
    both(a, b, 4000)
    a.snap("27_newgrip_go4")
    b.snap("27_newgrip_go4")
a.close()
b.close()
