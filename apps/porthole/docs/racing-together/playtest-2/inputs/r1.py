from duo2 import *
import sys

mode = sys.argv[1]
a, b = start()
if mode == "simul":
    a.tap(80, 21)
    b.tap(80, 21)
    both(a, b, 2000)
    a.snap("01_simul_2s")
    b.snap("01_simul_2s")
    both(a, b, 1500)
    a.snap("01_simul_3s")
    b.snap("01_simul_3s")
elif mode == "stagger":
    a.tap(80, 21)
    both(a, b, 330)
    b.tap(80, 21)
    both(a, b, 2000)
    a.snap("02_stagger")
    b.snap("02_stagger")
elif mode == "together_on_invite":
    a.tap(80, 21)
    both(a, b, 1500)
    b.tap(80, 21)
    both(a, b, 1500)
    a.snap("03_together_on_invite")
    b.snap("03_together_on_invite")
elif mode == "notnow":
    a.tap(80, 21)
    both(a, b, 1500)
    b.tap(84, 124)
    both(a, b, 800)
    a.snap("04_notnow")
    b.snap("04_notnow")
    both(a, b, 5000)
    a.snap("04_notnow_5s")
    a.tap(80, 21)
    both(a, b, 1500)
    a.snap("04_host_again")
    b.snap("04_host_again")
    b.tap(80, 96)
    both(a, b, 1500)
    a.snap("04_join_2nd")
    b.snap("04_join_2nd")
elif mode == "notnow_guest":
    a.tap(80, 21)
    both(a, b, 1500)
    b.tap(84, 124)
    both(a, b, 800)
    b.tap(80, 21)
    both(a, b, 1500)
    a.snap("05_guest_together_after_notnow")
    b.snap("05_guest_together_after_notnow")
    both(a, b, 3000)
    a.snap("05_3s")
    b.snap("05_3s")
elif mode == "lobby":
    to_lobby(a, b)
    a.snap("06_lobby")
    b.snap("06_lobby")
    print(b.do("ui"))
    a.tap(125, 76)
    both(a, b, 600)
    b.snap("06_lobby_next")
a.close()
b.close()
